"""Procedurally generates vector launcher icons and TV/handheld banner for OoT Native.

Zero external assets, zero trademarked silhouettes; all foreground paths use explicit
cubic Beziers / polylines bounded strictly inside the Android adaptive-icon safe zone.
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAWABLE = ROOT / 'android/app/src/main/res/drawable'


def _fmt(v: float) -> str:
    s = f'{v:.2f}'
    return s.rstrip('0').rstrip('.') if '.' in s else s


def arc_cubic_segments(cx: float, cy: float, r: float, a0_deg: float, a1_deg: float) -> list[str]:
    """Splits a circular arc into <=90-degree cubic Bezier segments starting after M."""
    a0 = math.radians(a0_deg)
    a1 = math.radians(a1_deg)
    span = a1 - a0
    steps = max(1, int(math.ceil(abs(span) / (math.pi / 2.0))))
    step = span / steps
    segs: list[str] = []
    for i in range(steps):
        t0 = a0 + i * step
        t1 = t0 + step
        k = (4.0 / 3.0) * math.tan((t1 - t0) / 4.0)
        x0, y0 = cx + r * math.cos(t0), cy + r * math.sin(t0)
        x3, y3 = cx + r * math.cos(t1), cy + r * math.sin(t1)
        x1 = x0 - k * r * math.sin(t0)
        y1 = y0 + k * r * math.cos(t0)
        x2 = x3 + k * r * math.sin(t1)
        y2 = y3 - k * r * math.cos(t1)
        segs.append(
            f'C{_fmt(x1)},{_fmt(y1)} {_fmt(x2)},{_fmt(y2)} {_fmt(x3)},{_fmt(y3)}'
        )
    return segs


def ring_sector_path(cx: float, cy: float, r_outer: float, r_inner: float, a0_deg: float, a1_deg: float) -> str:
    """Closed annular sector polygon/Bezier path from a0_deg to a1_deg."""
    a0 = math.radians(a0_deg)
    a1 = math.radians(a1_deg)
    sx, sy = cx + r_outer * math.cos(a0), cy + r_outer * math.sin(a0)
    ix, iy = cx + r_inner * math.cos(a1), cy + r_inner * math.sin(a1)
    parts = [f'M{_fmt(sx)},{_fmt(sy)}']
    parts.extend(arc_cubic_segments(cx, cy, r_outer, a0_deg, a1_deg))
    parts.append(f'L{_fmt(ix)},{_fmt(iy)}')
    parts.extend(arc_cubic_segments(cx, cy, r_inner, a1_deg, a0_deg))
    parts.append('Z')
    return ''.join(parts)


def circle_path(cx: float, cy: float, r: float) -> str:
    """Closed circle built from four cubic Bezier quadrants."""
    x0, y0 = cx + r, cy
    return f'M{_fmt(x0)},{_fmt(y0)}' + ''.join(arc_cubic_segments(cx, cy, r, 0.0, 360.0)) + 'Z'


def ring_path(cx: float, cy: float, r_outer: float, r_inner: float) -> str:
    """Closed annulus using evenOdd fillType."""
    outer = f'M{_fmt(cx + r_outer)},{_fmt(cy)}' + ''.join(arc_cubic_segments(cx, cy, r_outer, 0.0, 360.0)) + 'Z'
    inner = f'M{_fmt(cx + r_inner)},{_fmt(cy)}' + ''.join(arc_cubic_segments(cx, cy, r_inner, 360.0, 0.0)) + 'Z'
    return outer + inner


def diamond_path(cx: float, cy: float, rx: float, ry: float) -> str:
    return (
        f'M{_fmt(cx)},{_fmt(cy - ry)}'
        f'L{_fmt(cx + rx)},{_fmt(cy)}'
        f'L{_fmt(cx)},{_fmt(cy + ry)}'
        f'L{_fmt(cx - rx)},{_fmt(cy)}Z'
    )


def capsule_tick_path(cx: float, cy: float, r0: float, r1: float, half_w: float, angle_deg: float) -> str:
    """Rotated rectangular compass tick along ray angle_deg."""
    a = math.radians(angle_deg)
    ca, sa = math.cos(a), math.sin(a)
    px, py = -sa * half_w, ca * half_w
    pts = [
        (cx + r0 * ca - px, cy + r0 * sa - py),
        (cx + r1 * ca - px, cy + r1 * sa - py),
        (cx + r1 * ca + px, cy + r1 * sa + py),
        (cx + r0 * ca + px, cy + r0 * sa + py),
    ]
    return 'M' + 'L'.join(f'{_fmt(x)},{_fmt(y)}' for x, y in pts) + 'Z'


def rounded_bar_path(x: float, y: float, w: float, h: float) -> str:
    return f'M{_fmt(x)},{_fmt(y)}L{_fmt(x + w)},{_fmt(y)}L{_fmt(x + w)},{_fmt(y + h)}L{_fmt(x)},{_fmt(y + h)}Z'


