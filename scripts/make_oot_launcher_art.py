        f'    <path android:fillColor="#FFF8ECC2" android:pathData="{diamond_path(cx, cy, 4.0, 4.0)}" />',
        f'    <path android:fillColor="#556AD6B8" android:pathData="{"".join(bars[:4])}" />',
        f'    <path android:fillColor="#88E5BD5E" android:pathData="{"".join(bars[4:])}" />',
