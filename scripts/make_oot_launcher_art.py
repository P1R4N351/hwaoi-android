def render_monochrome() -> str:
    cx, cy = 54.0, 54.0
    ticks = ''.join(capsule_tick_path(cx, cy, 24.5, 29.0, 1.35, a) for a in (0, 90, 180, 270))
    wave_outer_l = ring_sector_path(cx, cy, 18.2, 15.6, 132.0, 228.0)
