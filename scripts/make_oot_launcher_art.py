    ticks = ''.join(capsule_tick_path(cx, cy, 41.0, 48.0, 2.1, a) for a in (0, 90, 180, 270))
    sub_ticks = ''.join(capsule_tick_path(cx, cy, 36.0, 39.5, 1.3, a) for a in (45, 135, 225, 315))
