        '    <path android:fillColor="#18E5BD5E" android:pathData="M0,26L320,6L320,20L0,40Z" />',
        '    <path android:fillColor="#145CE0B8" android:pathData="M0,148L320,128L320,144L0,164Z" />',
        f'    <path android:fillColor="#FFE5BD5E" android:fillType="evenOdd" android:pathData="{ring_path(cx, cy, 44.5, 40.0)}" />',
        f'    <path android:fillColor="#FFE5BD5E" android:pathData="{ticks}" />',
        f'    <path android:fillColor="#CCBF9B43" android:pathData="{sub_ticks}" />',
        f'    <path android:fillColor="#FFF3D98B" android:pathData="{wave_outer_l}{wave_outer_r}" />',
