"""Procedurally generates vector launcher icons and banner for AoI Native."""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAWABLE = ROOT / 'android/app/src/main/res/drawable'


def _fmt(val: float) -> str:
    """Format a coordinate cleanly without trailing zeros."""
    text = f'{val:.2f}'
    return text.rstrip('0').rstrip('.') if '.' in text else text


def arc_segments(
    cx: float, cy: float, r: float, a0_deg: float, a1_deg: float
) -> list[str]:
    """Build cubic Bezier segments approximating an arc from a0 to a1 deg."""
    assert r > 0.0, 'arc radius must be positive'
    a0, a1 = math.radians(a0_deg), math.radians(a1_deg)
    span = a1 - a0
    steps = max(1, int(math.ceil(abs(span) / (math.pi / 2.0))))
    step = span / steps
    segs: list[str] = []
    for i in range(steps):
        t0 = a0 + i * step
        t1 = t0 + step
        k = (4.0 / 3.0) * math.tan((t1 - t0) / 4.0)
        x0, y0 = cx + r * math.cos(t0), cy + r * math.sin(t0)
        x3, y3 = cx + r * math.cos(t1), cy + r * math.sin(t1)
        x1, y1 = x0 - k * r * math.sin(t0), y0 + k * r * math.cos(t0)
        x2, y2 = x3 + k * r * math.sin(t1), y3 - k * r * math.cos(t1)
        segs.append(
            f'C{_fmt(x1)},{_fmt(y1)} {_fmt(x2)},{_fmt(y2)} {_fmt(x3)},{_fmt(y3)}'
        )
    assert len(segs) == steps
    return segs


def ring_sector(
    cx: float, cy: float, r_out: float, r_in: float, a0: float, a1: float
) -> str:
    """Return a closed annular sector path."""
    assert r_out > r_in > 0.0, 'outer radius must exceed inner radius'
    rad0, rad1 = math.radians(a0), math.radians(a1)
    sx, sy = cx + r_out * math.cos(rad0), cy + r_out * math.sin(rad0)
    ix, iy = cx + r_in * math.cos(rad1), cy + r_in * math.sin(rad1)
    parts = [f'M{_fmt(sx)},{_fmt(sy)}']
    parts.extend(arc_segments(cx, cy, r_out, a0, a1))
    parts.append(f'L{_fmt(ix)},{_fmt(iy)}')
    parts.extend(arc_segments(cx, cy, r_in, a1, a0))
    parts.append('Z')
    return ''.join(parts)


def circle_path(cx: float, cy: float, r: float) -> str:
    """Return a closed circle path."""
    return f'M{_fmt(cx + r)},{_fmt(cy)}' + ''.join(arc_segments(cx, cy, r, 0.0, 360.0)) + 'Z'


def ring_path(cx: float, cy: float, r_out: float, r_in: float) -> str:
    """Return a closed even-odd ring path."""
    outer = f'M{_fmt(cx + r_out)},{_fmt(cy)}' + ''.join(arc_segments(cx, cy, r_out, 0.0, 360.0)) + 'Z'
    inner = f'M{_fmt(cx + r_in)},{_fmt(cy)}' + ''.join(arc_segments(cx, cy, r_in, 360.0, 0.0)) + 'Z'
    return outer + inner


def diamond_path(cx: float, cy: float, rx: float, ry: float) -> str:
    """Return a closed diamond path centered at (cx, cy)."""
    return (
        f'M{_fmt(cx)},{_fmt(cy - ry)}'
        f'L{_fmt(cx + rx)},{_fmt(cy)}'
        f'L{_fmt(cx)},{_fmt(cy + ry)}'
        f'L{_fmt(cx - rx)},{_fmt(cy)}Z'
    )


def crescent_comma_path(cx: float, cy: float, scale: float) -> str:
    """Return a closed golden-comma crescent path centered near (cx, cy)."""
    assert scale > 0.0, 'scale must be positive'
    assert 0.0 < cx < 320.0 and 0.0 < cy < 180.0, 'center out of viewport'
    s = scale
    x0, y0 = cx - 1.5 * s, cy - 11.0 * s
    pts = [
        (cx + 8.5 * s, cy - 11.0 * s, cx + 10.5 * s, cy - 1.0 * s, cx + 5.5 * s, cy + 7.5 * s),
        (cx + 1.5 * s, cy + 13.0 * s, cx - 7.0 * s, cy + 11.5 * s, cx - 9.0 * s, cy + 6.5 * s),
        (cx - 10.5 * s, cy + 2.5 * s, cx - 6.0 * s, cy + 0.5 * s, cx - 2.0 * s, cy + 2.0 * s),
        (cx + 2.0 * s, cy + 3.5 * s, cx + 3.5 * s, cy - 1.0 * s, cx + 1.0 * s, cy - 4.5 * s),
        (cx - 2.0 * s, cy - 8.5 * s, cx - 6.5 * s, cy - 7.0 * s, cx - 7.5 * s, cy - 3.5 * s),
        (cx - 8.5 * s, cy - 6.5 * s, cx - 6.0 * s, cy - 11.0 * s, x0, y0),
    ]
    segs = [f'M{_fmt(x0)},{_fmt(y0)}']
    for c1x, c1y, c2x, c2y, px, py in pts:
        segs.append(
            f'C{_fmt(c1x)},{_fmt(c1y)} {_fmt(c2x)},{_fmt(c2y)} {_fmt(px)},{_fmt(py)}'
        )
    segs.append('Z')
    return ''.join(segs)


def bar_path(x: float, y: float, w: float, h: float) -> str:
    """Return a closed vertical bar path."""
    return f'M{_fmt(x)},{_fmt(y)}L{_fmt(x + w)},{_fmt(y)}L{_fmt(x + w)},{_fmt(y + h)}L{_fmt(x)},{_fmt(y + h)}Z'


def _vector_wrap(width: str, height: str, vw: str, vh: str, body: list[str]) -> str:
    """Wrap vector paths in an Android VectorDrawable XML document."""
    assert width and height and vw and vh, 'viewport dimensions required'
    assert body, 'vector body must be non-empty'
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by scripts/make_aoi_launcher_art.py -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width}" android:height="{height}"',
        f'    android:viewportWidth="{vw}" android:viewportHeight="{vh}">',
    ]
    lines.extend(body)
    lines.extend(['</vector>', ''])
    return '\n'.join(lines)


def render_bg() -> str:
    """Render the obsidian concentric-ring adaptive background."""
    body = [
        '    <path android:fillColor="#FF171614" android:pathData="M0,0L108,0L108,108L0,108Z" />',
        f'    <path android:fillColor="#FF22201C" android:pathData="{circle_path(54.0, 54.0, 46.0)}" />',
        f'    <path android:fillColor="#FF2D2A24" android:pathData="{circle_path(54.0, 54.0, 34.0)}" />',
        '    <path android:fillColor="#18D99B26" android:pathData="M0,18L108,4L108,14L0,28Z" />',
        '    <path android:fillColor="#145AC8B8" android:pathData="M0,84L108,70L108,82L0,96Z" />',
    ]
    return _vector_wrap('108dp', '108dp', '108', '108', body)


def render_foreground() -> str:
    """Render the golden solar-arc & crescent jewel foreground inside [18, 90]."""
    cx, cy = 54.0, 54.0
    outer_ring = ring_path(cx, cy, 27.5, 24.8)
    arc_top = ring_sector(cx, cy, 21.8, 19.4, -142.0, -38.0)
    arc_bot = ring_sector(cx, cy, 21.8, 19.4, 38.0, 142.0)
    teal_l = ring_sector(cx, cy, 16.4, 14.2, 138.0, 222.0)
    teal_r = ring_sector(cx, cy, 16.4, 14.2, -42.0, 42.0)
    ticks = ''.join(diamond_path(cx + 29.0 * math.cos(math.radians(a)), cy + 29.0 * math.sin(math.radians(a)), 2.1, 2.1) for a in (0, 90, 180, 270))
    comma = crescent_comma_path(cx, cy, 0.92)
    core = diamond_path(cx + 2.0, cy - 2.0, 2.5, 2.5)
    body = [
        f'    <path android:fillColor="#FFD99B26" android:fillType="evenOdd" android:pathData="{outer_ring}" />',
        f'    <path android:fillColor="#FFE8B84B" android:pathData="{arc_top}{arc_bot}{ticks}" />',
        f'    <path android:fillColor="#FF5AC8B8" android:pathData="{teal_l}{teal_r}" />',
        f'    <path android:fillColor="#FFF2C96B" android:pathData="{comma}" />',
        f'    <path android:fillColor="#FF5AC8B8" android:pathData="{core}" />',
    ]
    assert len(body) == 5
    xml = _vector_wrap('108dp', '108dp', '108', '108', body)
    assert 'ic_aoi' not in xml and xml.startswith('<?xml')
    return xml


def render_monochrome() -> str:
    """Render the monochrome adaptive mask inside [18, 90]."""
    cx, cy = 54.0, 54.0
    outer_ring = ring_path(cx, cy, 27.5, 24.8)
    arc_top = ring_sector(cx, cy, 21.8, 19.4, -142.0, -38.0)
    arc_bot = ring_sector(cx, cy, 21.8, 19.4, 38.0, 142.0)
    comma = crescent_comma_path(cx, cy, 0.92)
    body = [
        f'    <path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="{outer_ring}" />',
        f'    <path android:fillColor="#FF000000" android:pathData="{arc_top}{arc_bot}{comma}" />',
    ]
    assert len(body) == 2
    xml = _vector_wrap('108dp', '108dp', '108', '108', body)
    assert '#FF000000' in xml
    return xml


def render_banner() -> str:
    """Render the 320x180 handheld/TV banner."""
    cx, cy = 92.0, 90.0
    outer_ring = ring_path(cx, cy, 45.0, 40.5)
    arc_top = ring_sector(cx, cy, 35.5, 31.8, -142.0, -38.0)
    arc_bot = ring_sector(cx, cy, 35.5, 31.8, 38.0, 142.0)
    teal_l = ring_sector(cx, cy, 27.0, 23.5, 138.0, 222.0)
    teal_r = ring_sector(cx, cy, 27.0, 23.5, -42.0, 42.0)
    comma = crescent_comma_path(cx, cy, 1.52)
    core = diamond_path(cx + 3.2, cy - 3.2, 4.0, 4.0)
    heights = (28.0, 48.0, 68.0, 52.0, 74.0, 56.0, 38.0, 60.0, 30.0)
    bars = [bar_path(176.0 + i * 13.0, cy - h / 2.0, 7.0, h) for i, h in enumerate(heights)]
    assert len(bars) == 9
    body = [
        '    <path android:fillColor="#FF171614" android:pathData="M0,0L320,0L320,180L0,180Z" />',
        f'    <path android:fillColor="#FF22201C" android:pathData="{circle_path(cx, cy, 76.0)}" />',
        f'    <path android:fillColor="#FF2D2A24" android:pathData="{circle_path(cx, cy, 56.0)}" />',
        '    <path android:fillColor="#18D99B26" android:pathData="M0,24L320,6L320,20L0,38Z" />',
        '    <path android:fillColor="#145AC8B8" android:pathData="M0,148L320,128L320,144L0,164Z" />',
        f'    <path android:fillColor="#FFD99B26" android:fillType="evenOdd" android:pathData="{outer_ring}" />',
        f'    <path android:fillColor="#FFE8B84B" android:pathData="{arc_top}{arc_bot}" />',
        f'    <path android:fillColor="#FF5AC8B8" android:pathData="{teal_l}{teal_r}" />',
        f'    <path android:fillColor="#FFF2C96B" android:pathData="{comma}" />',
        f'    <path android:fillColor="#FF5AC8B8" android:pathData="{core}" />',
        f'    <path android:fillColor="#555AC8B8" android:pathData="{"".join(bars[:4])}" />',
        f'    <path android:fillColor="#88F2C96B" android:pathData="{"".join(bars[4:])}" />',
    ]
    assert len(body) == 12
    return _vector_wrap('320dp', '180dp', '320', '180', body)


def main() -> int:
    """Write AoI launcher drawables and banner."""
    outputs = {
        DRAWABLE / 'ic_aoi_bg.xml': render_bg(),
        DRAWABLE / 'ic_aoi_foreground.xml': render_foreground(),
        DRAWABLE / 'ic_aoi_monochrome.xml': render_monochrome(),
        DRAWABLE / 'ic_banner.xml': render_banner(),
    }
    assert DRAWABLE.is_dir(), f'missing drawable dir: {DRAWABLE}'
    assert len(outputs) == 4
    for path, content in outputs.items():
        path.write_text(content, encoding='utf-8')
        print(f'wrote {path.relative_to(ROOT)} ({len(content)} B)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
